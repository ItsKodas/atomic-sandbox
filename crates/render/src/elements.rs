/// Display colour for `z` as sRGB bytes (what egui's `Color32` and a hex swatch use): the Jmol colour
/// for Z = 1..=118, the unknown-atom pink for 0 and anything beyond.
pub fn colour_srgb(z: u8) -> [u8; 3] { JMOL_SRGB.get(z as usize).copied().unwrap_or(JMOL_SRGB[0]) }

/// sRGB-encoded channel in 0..=1 to linear light (the IEC 61966-2-1 transfer function).
pub fn srgb_to_linear(c: f32) -> f32 { (if c <= 0.04045 { c / 12.92 } else { ((c + 0.055) / 1.055).powf(2.4) }).clamp(0.0, 1.0) }

/// Display colour as **linear** RGB for the GPU path: the sphere shader's output goes to an sRGB
/// surface (the window's, `gpu` picks an sRGB format; the screenshot's `Rgba8UnormSrgb`), which
/// encodes it, so feeding the linearised Jmol colour shows exactly `colour_srgb(z)` head-on.
pub fn colour(z: u8) -> [f32; 3] { colour_srgb(z).map(|b| srgb_to_linear(b as f32 / 255.0)) }

/// Display radius in Bohr: `0.35 · Z^(1/3)` (legibility, not physics).
pub fn radius(z: u8) -> f32 { 0.35 * (z.max(1) as f32).cbrt() }

/// Element symbol for `z` (Z = 1..=118; "?" for 0 and beyond): the workspace's one symbol table,
/// `units::elements` (M6 Task 10 — it was duplicated here and in `units::isotopes`).
pub use units::elements::symbol;

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(s: &str) -> [u8; 3] { std::array::from_fn(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap()) }

    #[test]
    fn spot_checks_against_the_jmol_table() {
        for (z, h) in [(1, "FFFFFF"), (2, "D9FFFF"), (6, "909090"), (7, "3050F8"), (8, "FF0D0D"), (16, "FFFF30"), (17, "1FF01F"),
                       (26, "E06633"), (79, "FFD123"), (92, "008FFF"), (109, "EB0026")] {
            assert_eq!(colour_srgb(z), hex(h), "Z = {z} ({})", symbol(z));
        }
    }

    #[test]
    fn beyond_jmol_and_out_of_range_use_the_unknown_atom_colour() {
        let unknown = hex("FF1493");
        for z in [0u8, 110, 118, 119, 200, 255] { assert_eq!(colour_srgb(z), unknown, "Z = {z}"); }
        assert_eq!(JMOL_SRGB.len(), 119);
    }

    #[test]
    fn linear_colour_round_trips_to_the_srgb_bytes() {
        for z in 0..=255u8 {
            let (lin, srgb) = (colour(z), colour_srgb(z));
            for k in 0..3 {
                assert!((0.0..=1.0).contains(&lin[k]));
                // linear -> sRGB encode -> byte, within 1/255
                let c = lin[k];
                let enc = if c <= 0.0031308 { 12.92 * c } else { 1.055 * c.powf(1.0 / 2.4) - 0.055 };
                assert!((enc * 255.0 - srgb[k] as f32).abs() <= 1.0, "Z = {z} channel {k}: {enc} vs {}", srgb[k]);
            }
        }
        assert!(colour(1).iter().all(|&c| c > 0.99999), "H is white");
    }
}
